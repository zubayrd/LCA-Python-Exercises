# Question 1: Variable Assignment and String Manipulation

# Store Variables

name = input("What is your name? ")

age = input("How old are you? ")

# Print output

print(f"Hello {name}. You are {age} years old.")

# Question 2: Integer Operations

# Store Variables

length = int(input("What is the length of the rectangle? "))

width = int(input("What is the length of the rectangle? "))

# Calculate area and print

area = length * width

print(area)

# Question 3: Working with Floats

# Store Variables

celcius = float(input("What is the temperature in Celcius? "))

# Convert to Fahrenheit and print output

fahrenheit = (celcius * 9/5) + 32

print(f"{fahrenheit:.2f}")
